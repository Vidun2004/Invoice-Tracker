"""Freeze your current .env into _embedded_env.py so PyInstaller bakes it into the exe.

Usage:
    cd desktop
    python build_embed.py        # reads .env -> writes _embedded_env.py
    python -m PyInstaller --onefile --windowed --name InvoiceTracker main.py
    # dist/InvoiceTracker.exe now connects without any .env file beside it.

Env vars at runtime still override embedded values. Re-run this script whenever
your Supabase URL/key changes, then rebuild.
"""
import os

BASE = os.path.dirname(os.path.abspath(__file__))


def read_env(path):
    vals = {}
    if not os.path.exists(path):
        return vals
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            vals[k.strip()] = v.strip().strip('"').strip("'")
    return vals


def main():
    vals = read_env(os.path.join(BASE, ".env"))
    url = vals.get("SUPABASE_URL", "")
    key = vals.get("SUPABASE_ANON_KEY", "")
    if not url or not key or "your-project" in url:
        print("ERROR: .env missing or still placeholder. Fill SUPABASE_URL / SUPABASE_ANON_KEY first.")
        raise SystemExit(1)
    out = os.path.join(BASE, "_embedded_env.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write('"""Auto-generated by build_embed.py — do not edit. Contains your Supabase connection."""\n')
        f.write(f"SUPABASE_URL = {url!r}\n")
        f.write(f"SUPABASE_ANON_KEY = {key!r}\n")
    print(f"Embedded OK -> {out} (URL {url[:30]}…, key ****{key[-4:]})")
    print("Now building with PyInstaller (icon + assets included)...")


if __name__ == "__main__":
    main()
